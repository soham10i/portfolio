"""Write sdk/vectors.json: canonical JSON, proposal hashes and signed approval messages, as the
Python implementation computes them. Both SDKs and the inbox are tested against this file, and
tests/test_api_unit.py checks it is what this script would write now.

    uv run python scripts/make_sdk_vectors.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

from cryptography.hazmat.primitives import serialization

from nexus.gate.gate import proposal_hash
from nexus.signing import Signer, approval_message
from nexus.store import canonical_json

OUT = Path(__file__).resolve().parent.parent / "sdk" / "vectors.json"

CANONICAL: list[Any] = [
    {"b": 1, "a": [3, 2, {"z": None, "y": True}], "c": "x"},
    {"€": 1, "é": 2, "e": 3, "\U0001f600": 4, "ﬁ": 5},
    [0, -1, 1.5, 0.1, 1e21, 1e-7, 123456789012, -0.0, 2**53 - 1, 1.0],
    {"s": 'quote " backslash \\ tab \t newline \n bell \u0007 slash / unicode \u2028 ü'},
    {"empty": {}, "list": [], "nested": {"deeper": {"deepest": [[], {}]}}},
    "plain string",
    False,
]

PROPOSAL = {
    "proposal_id": "0b9a1f6e-6c41-4f1c-9a53-2f4f4f0c8d11",
    "session_id": "5d8f8b2e-3f7a-4c55-9b1d-7c2e7a0e9f10",
    "action": "greenhouse:greenhouse.set_zone_setpoint",
    "params": {"zone": 2, "setpoint_c": 21.5},
    "rationale": "the operator asked for 21.5 °C in zone 2",
    "context": [{"source": "user", "ref": "request", "triggered": True}],
    "proposer": {"kind": "agent", "id": "planner"},
    "created_at": "2026-10-31T09:00:00Z",
}


def seed(name: str) -> bytes:
    return hashlib.sha256(f"nexus sdk vector key: {name}".encode()).digest()


def build() -> dict[str, Any]:
    modified = json.loads(json.dumps(PROPOSAL)) | {"params": {"zone": 2, "setpoint_c": 31.5}}
    signer = Signer.from_seed(seed("alice"))
    pkcs8 = signer._key.private_bytes(
        serialization.Encoding.DER, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    )
    approver = {"kind": "human", "id": "alice"}
    decision_id = "9f0e2d4c-1b3a-4e5f-8a7b-6c5d4e3f2a1b"
    digest = proposal_hash(PROPOSAL)
    message = approval_message(decision_id, digest, approver)
    return {
        "about": "Generated by scripts/make_sdk_vectors.py from the Python implementation. Do not edit.",
        "canonical": [{"value": v, "json": canonical_json(v).decode()} for v in CANONICAL],
        "proposal_hash": [
            {"proposal": PROPOSAL, "hash": digest},
            {"proposal": modified, "hash": proposal_hash(modified)},
        ],
        "approval": {
            "decision_id": decision_id,
            "proposal_hash": digest,
            "approver": approver,
            "message": message.decode(),
            "key": {
                "pkcs8_hex": pkcs8.hex(),
                "public_key": signer.public_key,
                "key_id": signer.key_id,
            },
            "signature": signer.sign(message),
        },
    }


def render() -> str:
    return json.dumps(build(), indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}", file=sys.stderr)
